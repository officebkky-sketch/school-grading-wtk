// บันทึกการประเมินพัฒนาการระดับบุคคล
export interface KindergartenStudentAssessment {
  studentId: string;
  classLevel: string; // 'อ.1', 'อ.2', 'อ.3'
  academicYear: string;
  term: 1 | 2;
  // บันทึกระดับคุณภาพทั้ง 12 มาตรฐาน: key คือ standard id (1 - 12)
  standards: Record<number, QualityLevel>;
  // บันทึกเฉพาะตัวบ่งชี้ย่อย (Optional สำหรับเจาะลึก)
  indicatorNotes?: Record<string, string>;
  // ความเห็นและข้อเสนอแนะของครูประจำชั้น
  teacherComment?: string;
  // บันทึกสุขภาพและสุขนิสัย
  healthInfo?: {
    weight?: number;
    height?: number;
    teethCheck?: 'ปกติ' | 'มีฟันผุ' | 'รอรับการรักษา';
    teethCavitiesCount?: number;
    hairCleanliness?: 'สะอาด' | 'ควรปรับปรุง';
    nailCleanliness?: 'สะอาด' | 'ควรปรับปรุง';
    nutritionStatus?: string; // เช่น 'สมส่วน', 'ท้วม', 'เริ่มอ้วน'
    growthHeightStatus?: string; // เช่น 'สูงตามเกณฑ์', 'เตี้ย'
  };
  // เวลาเรียน
  attendance?: {
    presentDays: number;
    totalDays: number;
    leaveDays?: number;
    sickDays?: number;
  };
  updatedAt?: string;
}
